/* ---- The tail ------------------------------------------------------------------------------
 * In units G m = c = 1 (the ADM mass M of the tail taken as m, as the order allows), with the
 * Newtonian quadrupole I_ij = nu x^<i x^j> of the relative motion, eq. (acctailCM) reads
 *   a_tail = -(4/5) x^j T_ij + (8/5) x^j [I3_ij (ln r)''' + 3 I4_ij (ln r)'' + 3 I5_ij (ln r)']
 *            - (2 / (5 nu)) (n / r) I3_jk I3_jk,
 * Ik the k-th time derivative, T_ij = Pf_{2r} int dt' I6_ij(t') / |t - t'| the hereditary
 * integral over the whole orbit, past and future, with the Hadamard scale 2 r(t); the middle
 * terms come from the variation of that time-dependent scale. The dissipative part, eq.
 * (acctaildiss), is a_diss = -(4/5) x^j D_ij with D_ij the time-antisymmetric integral
 * int_0^inf dtau ln(tau / 2r) [I7(t - tau) + I7(t + tau)].
 *
 * The integrals need the orbit at all times. To the order of the term (the tail is 4PN; a
 * 1PN change of the orbit inside it is 5PN) the orbit inside them is the osculating Newtonian
 * (Kepler) orbit through the current state, periodic with mean motion n, on which I6 has the
 * Fourier series sum_p f_p e^{i p l} in the mean anomaly l (f_0 = 0). Then (eq.
 * tailfactorFourier, with l = 0 now)
 *   T = -2 sum_{p != 0} f_p [ln(2 |p| n r) + gamma_E]
 *     = -2 [ln(2 n r) + gamma_E] I6(now) - 4 sum_{p >= 1} ln p Re f_p,
 *   D = sum_{p != 0} (-i pi sgn p) f_p = 2 pi sum_{p >= 1} Im f_p,
 * the second from int_0^inf ln(tau) cos(w tau) dtau = -pi / (2 |w|). For a circular orbit only
 * p = 2 is present: T = -2 [ln(4 sqrt(G m / (r c^2))) + gamma_E] I6, the closed form of eq. (T6),
 * and the tail adds to Omega^2 the term (128/5) nu gamma^4 [ln(16 gamma) + 2 gamma_E + 1/2]
 * G m / r^3 of eq. (omtail); the dissipative part brings the factor 4 pi x^(3/2) of the flux.
 *
 * f_p is computed by the trapezoidal rule in the eccentric anomaly E (uniform samples, the
 * weight dl/dE = r / a): exponentially convergent for the periodic analytic integrand, and the
 * fast passage at periapsis is resolved by E as it would not be by l. I6 at each sample is
 * computed directly (Taylor series of the Kepler motion), not as (i p n)^6 times the
 * coefficients of I, which would amplify their rounding by p^6. The harmonics are kept while
 * p^6 rho^p > 1e-13, rho = e exp(sqrt(1 - e^2)) / (1 + sqrt(1 - e^2)) the ratio of the Kapteyn
 * series of the Kepler motion, with 2 P + 16 samples (P = 11, 25, 60, 132, 360, 900 for e =
 * 0.01, 0.1, 0.3, 0.5, 0.7, 0.82; an orbit of e = 0.8 with only 512 harmonics was still 3e-8
 * off). Against the same tail from the Fourier coefficients of I computed with mpmath (30
 * digits, 256-1024 samples, p up to 220): 4e-16 for a circular orbit, 9e-15 at e = 0.05, 2e-13
 * at e = 0.2 and 0.4, 3e-14 near the periapsis of e = 0.6 and 3e-10 at its apoapsis, where the
 * tail is 4e4 times smaller than at the periapsis and the rounding of the periapsis samples
 * dominates. Up to 1024 harmonics (e < 0.83). */

enum {
  TAYLOR = 7, /* Taylor coefficients x^(k) / k! for k = 0..6 */
  TAIL_MAX_HARMONICS = 1024,
  TAIL_BLOCK = 16 /* samples processed together, so that ln p is taken once per block */
};

#define MYB_EULER_GAMMA 0.57721566490153286061
#define MYB_TWO_PI 6.283185307179586477

/* Taylor coefficients xs[k] = x^(k)(0) / k!, k = 0..6, of the Newtonian motion x'' = -x / r^3
 * (G m = 1) through (x, v), and f[k] those of r^2, k = 0..4: with s = f^(-3/2) as power series,
 * k f_0 s_k = sum_{j=1..k} (-3/2 j - (k - j)) f_j s_{k-j} and
 * (k + 1)(k + 2) x_{k+2} = -sum_{j=0..k} s_j x_{k-j}. */
static void kepler_taylor(const double x[3], const double v[3], double xs[TAYLOR][3],
                          double f[TAYLOR - 2]) {
  double s[TAYLOR - 2];
  for (int i = 0; i < 3; ++i) {
    xs[0][i] = x[i];
    xs[1][i] = v[i];
  }
  for (int k = 0; k < TAYLOR - 2; ++k) {
    double fk = 0.0;
    for (int j = 0; j <= k; ++j) {
      fk += myb_vec3_dot(xs[j], xs[k - j]);
    }
    f[k] = fk;
    if (k == 0) {
      s[0] = 1.0 / (f[0] * sqrt(f[0]));
    } else {
      double acc = 0.0;
      for (int j = 1; j <= k; ++j) {
        acc += (-1.5 * j - (double)(k - j)) * f[j] * s[k - j];
      }
      s[k] = acc / ((double)k * f[0]);
    }
    for (int i = 0; i < 3; ++i) {
      double acc = 0.0;
      for (int j = 0; j <= k; ++j) {
        acc += s[j] * xs[k - j][i];
      }
      xs[k + 2][i] = -acc / ((double)(k + 1) * (double)(k + 2));
    }
  }
}

/* (I^(order) y) / nu = order! [sum_j x_j (x_{order-j}.y) - y / 3 sum_j x_j.x_{order-j}] */
static void quadrupole_dot(const double xs[TAYLOR][3], int order, double factorial,
                           const double y[3], double out[3]) {
  double acc[3] = {0.0, 0.0, 0.0};
  double trace = 0.0;
  for (int j = 0; j <= order; ++j) {
    const double d = myb_vec3_dot(xs[order - j], y);
    for (int i = 0; i < 3; ++i) {
      acc[i] += xs[j][i] * d;
    }
    trace += myb_vec3_dot(xs[j], xs[order - j]);
  }
  for (int i = 0; i < 3; ++i) {
    out[i] = factorial * (acc[i] - trace / 3.0 * y[i]);
  }
}

/* The number of harmonics for the eccentricity e: the smallest P with 6 ln P + P ln rho <
 * ln 1e-13 (at least 4), or 0 when more than TAIL_MAX_HARMONICS are needed. */
static int tail_harmonics(double e) {
  if (!(e > 1e-12)) {
    return 4;
  }
  const double q = sqrt((1.0 - e) * (1.0 + e));
  const double log_rho = myb_log(e) + q - myb_log(1.0 + q);
  const double target = -29.933606208922594; /* ln 1e-13 */
  double p = 4.0;
  for (int it = 0; it < 40; ++it) { /* p = (6 ln p - ln 1e-13) / (-ln rho): a contraction */
    const double next = (6.0 * myb_log(p) - target) / -log_rho;
    if (!(next > 4.0)) {
      return 4;
    }
    if (next > 2.0 * (double)TAIL_MAX_HARMONICS) {
      return 0;
    }
    if (fabs(next - p) < 0.5) {
      p = next;
      break;
    }
    p = next;
  }
  const int harmonics = (int)p + 1;
  return harmonics <= TAIL_MAX_HARMONICS ? harmonics : 0;
}

/* The tail acceleration (units G m = c = 1) of the state (x, v), its conservative part when
 * `conservative`, its dissipative part when `dissipative`, added to out. MYB_E_DOMAIN when the
 * osculating orbit is unbound or too eccentric. */
static myb_status tail_acceleration(double nu, const double x[3], const double v[3],
                                    int conservative, int dissipative, double out[3]) {
  const double r0 = myb_vec3_norm(x);
  const double v2 = myb_vec3_dot(v, v);
  const double inv_a = 2.0 / r0 - v2;
  if (!(inv_a > 0.0)) {
    return MYB_E_DOMAIN;
  }
  const double a = 1.0 / inv_a;
  const double sa = sqrt(a);
  const double s0 = myb_vec3_dot(x, v) / sa; /* e sin E0 */
  const double k0 = r0 * v2 - 1.0;           /* e cos E0 = 1 - r0 / a */
  const double e = sqrt(s0 * s0 + k0 * k0);
  const double n = 1.0 / (a * sa);
  const int harmonics = tail_harmonics(e);
  if (harmonics == 0) {
    return MYB_E_DOMAIN;
  }
  const int samples = 2 * harmonics + 16;
  double sc[3] = {0.0, 0.0, 0.0}; /* sum_k I6_k.x w_k sum_p ln p cos(p l_k) */
  double sd[3] = {0.0, 0.0, 0.0}; /* sum_k I6_k.x w_k sum_p sin(p l_k) */
  for (int k0b = 0; k0b < samples; k0b += TAIL_BLOCK) {
    const int count = samples - k0b < TAIL_BLOCK ? samples - k0b : TAIL_BLOCK;
    double fw[TAIL_BLOCK][3];
    double c1[TAIL_BLOCK];
    double s1[TAIL_BLOCK];
    double cp[TAIL_BLOCK];
    double sp[TAIL_BLOCK];
    double kc[TAIL_BLOCK];
    double ks[TAIL_BLOCK];
    for (int j = 0; j < count; ++j) {
      /* the Kepler orbit at the eccentric-anomaly offset dE from now (f and g functions) */
      const double de = MYB_TWO_PI * (double)(k0b + j) / (double)samples;
      const double c = myb_cos(de);
      const double s = myb_sin(de);
      const double r = a * (1.0 - k0 * c + s0 * s);
      const double ff = 1.0 - a / r0 * (1.0 - c);
      const double gg = a * sa * (s0 * (1.0 - c) + r0 / a * s);
      const double fd = -sa * s / (r * r0);
      const double gd = 1.0 - a / r * (1.0 - c);
      const double dl = de + s0 * (1.0 - c) - k0 * s; /* mean anomaly from now */
      double xk[3];
      double vk[3];
      for (int i = 0; i < 3; ++i) {
        xk[i] = ff * x[i] + gg * v[i];
        vk[i] = fd * x[i] + gd * v[i];
      }
      double xs[TAYLOR][3];
      double f[TAYLOR - 2];
      kepler_taylor(xk, vk, xs, f);
      double i6[3];
      quadrupole_dot(xs, 6, 720.0, x, i6);
      const double w = r / a;
      for (int i = 0; i < 3; ++i) {
        fw[j][i] = i6[i] * w;
      }
      c1[j] = myb_cos(dl);
      s1[j] = myb_sin(dl);
      cp[j] = c1[j];
      sp[j] = s1[j];
      kc[j] = 0.0;
      ks[j] = 0.0;
    }
    for (int p = 1; p <= harmonics; ++p) {
      const double lp = p > 1 ? myb_log((double)p) : 0.0;
      for (int j = 0; j < count; ++j) {
        kc[j] += lp * cp[j];
        ks[j] += sp[j];
        const double cn = cp[j] * c1[j] - sp[j] * s1[j];
        sp[j] = sp[j] * c1[j] + cp[j] * s1[j];
        cp[j] = cn;
      }
    }
    for (int j = 0; j < count; ++j) {
      for (int i = 0; i < 3; ++i) {
        sc[i] += fw[j][i] * kc[j];
        sd[i] += fw[j][i] * ks[j];
      }
    }
  }
  /* the instantaneous pieces at the current state */
  double xs[TAYLOR][3];
  double f[TAYLOR - 2];
  kepler_taylor(x, v, xs, f);
  const double inv_samples = 1.0 / (double)samples;
  if (conservative) {
    double i3[3];
    double i4[3];
    double i5[3];
    double i6[3];
    quadrupole_dot(xs, 3, 6.0, x, i3);
    quadrupole_dot(xs, 4, 24.0, x, i4);
    quadrupole_dot(xs, 5, 120.0, x, i5);
    quadrupole_dot(xs, 6, 720.0, x, i6);
    /* d^k ln r / dt^k from g = ln f: k f_0 g_k = k f_k - sum_{j=1..k-1} j g_j f_{k-j} */
    const double g1 = f[1] / f[0];
    const double g2 = (2.0 * f[2] - g1 * f[1]) / (2.0 * f[0]);
    const double g3 = (3.0 * f[3] - g1 * f[2] - 2.0 * g2 * f[1]) / (3.0 * f[0]);
    const double l1 = 0.5 * g1;
    const double l2 = g2;       /* 2! g2 / 2 */
    const double l3 = 3.0 * g3; /* 3! g3 / 2 */
    /* I3:I3 / (36 nu^2) = sum (T_ab - delta_ab tr / 3)^2, T_ab = sum_j x_j,a x_{3-j},b */
    double t[3][3];
    for (int p = 0; p < 3; ++p) {
      for (int q = 0; q < 3; ++q) {
        double acc = 0.0;
        for (int j = 0; j <= 3; ++j) {
          acc += xs[j][p] * xs[3 - j][q];
        }
        t[p][q] = acc;
      }
    }
    const double tr = t[0][0] + t[1][1] + t[2][2];
    double tt = 0.0;
    for (int p = 0; p < 3; ++p) {
      for (int q = 0; q < 3; ++q) {
        tt += t[p][q] * t[p][q];
      }
    }
    const double i3i3 = 36.0 * nu * nu * (tt - tr * tr / 3.0);
    const double scale = 2.0 * (myb_log(2.0 * n * r0) + MYB_EULER_GAMMA);
    const double r2 = r0 * r0;
    for (int i = 0; i < 3; ++i) {
      const double tx = nu * (-scale * i6[i] - 4.0 * inv_samples * sc[i]);
      const double inst = nu * (i3[i] * l3 + 3.0 * i4[i] * l2 + 3.0 * i5[i] * l1);
      out[i] += -0.8 * tx + 1.6 * inst - 0.4 / nu * x[i] / r2 * i3i3;
    }
  }
  if (dissipative) {
    for (int i = 0; i < 3; ++i) {
      out[i] += -0.8 * nu * (-MYB_TWO_PI * inv_samples * sd[i]);
    }
  }
  return MYB_OK;
}

/* ---- Spin-orbit terms ----------------------------------------------------------------------
 * In units G m = c = 1, with S = S1 + S2 and Sigma = S2 / X2 - S1 / X1 of the spins
 * S_A = X_A^2 chi_A (X_A = m_A / m), dm = X1 - X2, ri = 1/r, rd = n.v, v2 = v.v:
 *   a_SO(2.5PN) = (1/r^3) [b1 + b2 / r]     (arXiv:1212.5520, eq. AiSCMc5),
 *   a_SO(3.5PN) = (1/r^3) [b1 + b2 / r + b3 / r^2]   (eq. AiSCMc7),
 * each b a combination of n, v, n x S, n x Sigma, S x v, Sigma x v with the mixed products
 * (n, S, v), (n, Sigma, v). */
static void spin_orbit_terms(unsigned orders, double nu, double dm, double ri, double rd, double v2,
                             const double n[3], const double bv[3], const double s[3],
                             const double z[3], double acc[3]) {
  double nxs[3];
  double nxz[3];
  double sxv[3];
  double zxv[3];
  myb_vec3_cross(n, s, nxs);
  myb_vec3_cross(n, z, nxz);
  myb_vec3_cross(s, bv, sxv);
  myb_vec3_cross(z, bv, zxv);
  const double nsv = myb_vec3_dot(n, sxv);
  const double nzv = myb_vec3_dot(n, zxv);
  const double nu2 = nu * nu;
  const double ri2 = ri * ri;
  const double ri3 = ri2 * ri;
  const double ri4 = ri2 * ri2;
  const double ri5 = ri4 * ri;
  const double rd2 = rd * rd;
  const double rd3 = rd2 * rd;
  const double rd4 = rd2 * rd2;
  const double rd5 = rd4 * rd;
  const double v4 = v2 * v2;
  double cn = 0.0;
  double cv = 0.0;
  double cs = 0.0;
  double cz = 0.0;
  double csv = 0.0;
  double czv = 0.0;
  if (orders & MYB_PN_SO25) {
    cn += nzv * ri3 * (-12.0 * v2 * dm * nu + 15.0 * rd2 * dm * nu) +
          nsv * ri3 * (-24.0 * v2 * nu + 30.0 * rd2 * nu) +
          nzv * ri4 * (24.0 * dm + 37.0 / 2.0 * dm * nu) + nsv * ri4 * (44.0 + 33.0 * nu);
    cv += nzv * ri3 * (9.0 / 2.0 * rd * dm - 6.0 * rd * dm * nu) +
          nsv * ri3 * (21.0 / 2.0 * rd - 21.0 / 2.0 * rd * nu);
    cs += ri3 * (-3.0 / 2.0 * rd * v2 + 45.0 / 2.0 * rd * v2 * nu - 45.0 / 2.0 * rd3 * nu) +
          ri4 * (-28.0 * rd - 29.0 * rd * nu);
    cz += ri3 * (-3.0 / 2.0 * rd * v2 * dm + 12.0 * rd * v2 * dm * nu - 15.0 * rd3 * dm * nu) +
          ri4 * (-12.0 * rd * dm - 31.0 / 2.0 * rd * dm * nu);
    csv += ri3 * (14.0 * v2 * nu - 3.0 / 2.0 * rd2 - 15.0 * rd2 * nu) + ri4 * (-24.0 - 19.0 * nu);
    czv += ri3 * (7.0 * v2 * dm * nu - 3.0 / 2.0 * rd2 * dm - 9.0 * rd2 * dm * nu) +
           ri4 * (-12.0 * dm - 19.0 / 2.0 * dm * nu);
  }
  if (orders & MYB_PN_SO35) {
    cn += nzv * ri3 *
              (-9.0 * v4 * dm * nu + 24.0 * v4 * dm * nu2 + 30.0 * rd2 * v2 * dm * nu -
               75.0 * rd2 * v2 * dm * nu2 - 105.0 / 4.0 * rd4 * dm * nu +
               315.0 / 4.0 * rd4 * dm * nu2) +
          nsv * ri3 *
              (-18.0 * v4 * nu + 48.0 * v4 * nu2 + 60.0 * rd2 * v2 * nu - 150.0 * rd2 * v2 * nu2 -
               105.0 / 2.0 * rd4 * nu + 315.0 / 2.0 * rd4 * nu2) +
          nzv * ri4 *
              (-131.0 / 8.0 * v2 * dm * nu - 19.0 * v2 * dm * nu2 + 3147.0 / 8.0 * rd2 * dm * nu +
               255.0 / 4.0 * rd2 * dm * nu2) +
          nsv * ri4 *
              (-217.0 / 4.0 * v2 * nu - 28.0 * v2 * nu2 + 1635.0 / 2.0 * rd2 * nu +
               117.0 * rd2 * nu2) +
          nzv * ri5 * (-111.0 / 2.0 * dm - 441.0 / 4.0 * dm * nu + 5.0 * dm * nu2) +
          nsv * ri5 * (-195.0 / 2.0 - 749.0 / 4.0 * nu + 8.0 * nu2);
    cv += nzv * ri3 *
              (3.0 / 8.0 * rd * v2 * dm + 15.0 / 4.0 * rd * v2 * dm * nu +
               141.0 / 8.0 * rd * v2 * dm * nu2 - 15.0 / 2.0 * rd3 * dm * nu -
               105.0 / 4.0 * rd3 * dm * nu2) +
          nsv * ri3 *
              (3.0 / 8.0 * rd * v2 + 27.0 / 8.0 * rd * v2 * nu + 249.0 / 8.0 * rd * v2 * nu2 -
               15.0 / 2.0 * rd3 * nu - 195.0 / 4.0 * rd3 * nu2) +
          nzv * ri4 * (-381.0 / 2.0 * rd * dm * nu - 25.0 * rd * dm * nu2) +
          nsv * ri4 * (-777.0 / 2.0 * rd * nu - 87.0 / 2.0 * rd * nu2);
    cs += ri3 * (-3.0 / 8.0 * rd * v4 + 165.0 / 8.0 * rd * v4 * nu - 441.0 / 8.0 * rd * v4 * nu2 -
                 105.0 / 2.0 * rd3 * v2 * nu + 585.0 / 4.0 * rd3 * v2 * nu2 +
                 315.0 / 8.0 * rd5 * nu - 945.0 / 8.0 * rd5 * nu2) +
          ri4 * (1067.0 / 4.0 * rd * v2 * nu + 79.0 / 2.0 * rd * v2 * nu2 -
                 1215.0 / 2.0 * rd3 * nu - 105.0 * rd3 * nu2) +
          ri5 * (121.0 / 2.0 * rd + 65.0 * rd * nu - 8.0 * rd * nu2);
    cz += ri3 * (-3.0 / 8.0 * rd * v4 * dm + 57.0 / 4.0 * rd * v4 * dm * nu -
                 237.0 / 8.0 * rd * v4 * dm * nu2 - 75.0 / 2.0 * rd3 * v2 * dm * nu +
                 345.0 / 4.0 * rd3 * v2 * dm * nu2 + 105.0 / 4.0 * rd5 * dm * nu -
                 525.0 / 8.0 * rd5 * dm * nu2) +
          ri4 * (945.0 / 8.0 * rd * v2 * dm * nu + 23.0 * rd * v2 * dm * nu2 -
                 2193.0 / 8.0 * rd3 * dm * nu - 279.0 / 4.0 * rd3 * dm * nu2) +
          ri5 * (57.0 / 2.0 * rd * dm + 85.0 / 4.0 * rd * dm * nu - 6.0 * rd * dm * nu2);
    csv += ri3 * (21.0 / 2.0 * v4 * nu - 28.0 * v4 * nu2 - 3.0 / 8.0 * rd2 * v2 -
                  255.0 / 8.0 * rd2 * v2 * nu + 627.0 / 8.0 * rd2 * v2 * nu2 +
                  225.0 / 8.0 * rd4 * nu - 585.0 / 8.0 * rd4 * nu2) +
           ri4 * (197.0 / 4.0 * v2 * nu + 14.0 * v2 * nu2 - 352.0 * rd2 * nu -
                  123.0 / 2.0 * rd2 * nu2) +
           ri5 * (105.0 / 2.0 + 137.0 / 2.0 * nu);
    czv += ri3 * (11.0 / 2.0 * v4 * dm * nu - 14.0 * v4 * dm * nu2 - 3.0 / 8.0 * rd2 * v2 * dm -
                  69.0 / 4.0 * rd2 * v2 * dm * nu + 351.0 / 8.0 * rd2 * v2 * dm * nu2 +
                  15.0 * rd4 * dm * nu - 315.0 / 8.0 * rd4 * dm * nu2) +
           ri4 * (177.0 / 8.0 * v2 * dm * nu + 7.0 * v2 * dm * nu2 - 1325.0 / 8.0 * rd2 * dm * nu -
                  147.0 / 4.0 * rd2 * dm * nu2) +
           ri5 * (57.0 / 2.0 * dm + 65.0 / 2.0 * dm * nu);
  }
  for (int i = 0; i < 3; ++i) {
    acc[i] += cn * n[i] + cv * bv[i] + cs * nxs[i] + cz * nxz[i] + csv * sxv[i] + czv * zxv[i];
  }
}

/* The precession of spin 1 beyond the leading order, Omega_1 = (n x v) (alpha_2PN +
 * alpha_3PN) in units G m = c = 1 (arXiv:1212.5520 eq. Omega1CM); spin 2: dm -> -dm. */
static double precession_higher(unsigned orders, double nu, double dm, double ri, double rd,
                                double v2) {
  const double nu2 = nu * nu;
  const double nu3 = nu2 * nu;
  const double ri2 = ri * ri;
  const double ri3 = ri2 * ri;
  const double ri4 = ri2 * ri2;
  const double rd2 = rd * rd;
  const double rd4 = rd2 * rd2;
  const double v4 = v2 * v2;
  double alpha = 0.0;
  if (orders & MYB_PN_SO25) {
    alpha += 1.0 / 16.0 * ri2 * v2 + 11.0 / 8.0 * ri2 * v2 * nu - 3.0 / 8.0 * ri2 * v2 * nu2 -
             1.0 / 16.0 * ri2 * v2 * dm + 1.0 / 2.0 * ri2 * v2 * dm * nu -
             3.0 / 2.0 * ri2 * rd2 * nu + 3.0 / 4.0 * ri2 * rd2 * nu2 -
             3.0 / 2.0 * ri2 * rd2 * dm * nu - 1.0 / 4.0 * ri3 - 3.0 / 8.0 * ri3 * nu +
             1.0 / 2.0 * ri3 * nu2 + 1.0 / 4.0 * ri3 * dm - 1.0 / 8.0 * ri3 * dm * nu;
  }
  if (orders & MYB_PN_SO35) {
    alpha +=
        1.0 / 32.0 * ri2 * v4 + 19.0 / 16.0 * ri2 * v4 * nu - 31.0 / 8.0 * ri2 * v4 * nu2 +
        17.0 / 16.0 * ri2 * v4 * nu3 - 1.0 / 32.0 * ri2 * v4 * dm + 3.0 / 4.0 * ri2 * v4 * dm * nu -
        11.0 / 8.0 * ri2 * v4 * dm * nu2 - 3.0 * ri2 * rd2 * v2 * nu +
        291.0 / 32.0 * ri2 * rd2 * v2 * nu2 - 45.0 / 16.0 * ri2 * rd2 * v2 * nu3 -
        3.0 * ri2 * rd2 * v2 * dm * nu + 177.0 / 32.0 * ri2 * rd2 * v2 * dm * nu2 +
        15.0 / 8.0 * ri2 * rd4 * nu - 195.0 / 32.0 * ri2 * rd4 * nu2 +
        15.0 / 16.0 * ri2 * rd4 * nu3 + 15.0 / 8.0 * ri2 * rd4 * dm * nu -
        75.0 / 32.0 * ri2 * rd4 * dm * nu2 + 3.0 / 16.0 * ri3 * v2 + 27.0 / 4.0 * ri3 * v2 * nu +
        75.0 / 32.0 * ri3 * v2 * nu2 - 9.0 / 8.0 * ri3 * v2 * nu3 - 3.0 / 16.0 * ri3 * v2 * dm +
        9.0 / 8.0 * ri3 * v2 * dm * nu + 35.0 / 32.0 * ri3 * v2 * dm * nu2 + 1.0 / 4.0 * ri3 * rd2 -
        525.0 / 32.0 * ri3 * rd2 * nu - 159.0 / 16.0 * ri3 * rd2 * nu2 +
        13.0 / 4.0 * ri3 * rd2 * nu3 - 1.0 / 4.0 * ri3 * rd2 * dm -
        75.0 / 32.0 * ri3 * rd2 * dm * nu - 87.0 / 16.0 * ri3 * rd2 * dm * nu2 + 7.0 / 16.0 * ri4 -
        9.0 / 4.0 * ri4 * nu - 9.0 / 8.0 * ri4 * nu2 + 1.0 / 2.0 * ri4 * nu3 -
        7.0 / 16.0 * ri4 * dm - 1.0 / 8.0 * ri4 * dm * nu - 1.0 / 8.0 * ri4 * dm * nu2;
  }
  return alpha;
}

/* Will 2005 eq. (B3b) in units G = m = c = 1 with the true spins S_A = X_A^2 chi_A: calS = S1 + S2,
 * xi = (m2/m1) S1 + (m1/m2) S2 = nu (chi1 + chi2), L = x x v. */
static void spin_orbit_reaction(double nu, double ri, double rd, double v2, const double n[3],
                                const double bv[3], const double s[3], const double xi[3],
                                double acc[3]) {
  double nxv[3];
  myb_vec3_cross(n, bv, nxv);
  const double ls = myb_vec3_dot(nxv, s) / ri; /* L.calS, L = r n x v */
  const double lxi = myb_vec3_dot(nxv, xi) / ri;
  const double ri2 = ri * ri;
  const double ri4 = ri2 * ri2;
  const double ri5 = ri4 * ri;
  const double ri6 = ri4 * ri2;
  const double rd2 = rd * rd;
  const double rd3 = rd2 * rd;
  const double rd4 = rd2 * rd2;
  const double v4 = v2 * v2;
  const double rr_n =
      nu * (ls * (-24.0 * ri5 * rd * v2 - 56.0 * ri5 * rd3 - 453.0 / 5.0 * ri6 * rd) +
            lxi * (-24.0 * ri5 * rd * v2 - 56.0 * ri5 * rd3 - 458.0 / 5.0 * ri6 * rd));
  const double rr_v = nu * (ls * (-87.0 / 5.0 * ri5 * v2 + 135.0 * ri5 * rd2 + 901.0 / 15.0 * ri6) +
                            lxi * (-72.0 / 5.0 * ri5 * v2 + 120.0 * ri5 * rd2 + 264.0 / 5.0 * ri6));
  const double rr_nxs =
      nu * (-31.0 / 10.0 * ri4 * v4 + 26.0 * ri4 * rd2 * v2 - 49.0 / 2.0 * ri4 * rd4 +
            689.0 / 30.0 * ri5 * v2 - 537.0 / 10.0 * ri5 * rd2 - 2.0 / 15.0 * ri6);
  const double rr_nxxi =
      nu * (-23.0 / 2.0 * ri4 * v4 + 113.0 * ri4 * rd2 * v2 - 259.0 / 2.0 * ri4 * rd4 +
            869.0 / 30.0 * ri5 * v2 - 849.0 / 10.0 * ri5 * rd2 - 22.0 / 15.0 * ri6);
  const double rr_vxs =
      nu * (32.0 / 5.0 * ri4 * rd * v2 + 2.0 * ri4 * rd3 + 728.0 / 15.0 * ri5 * rd);
  const double rr_vxxi =
      nu * (-97.0 / 5.0 * ri4 * rd * v2 + 47.0 * ri4 * rd3 + 772.0 / 15.0 * ri5 * rd);
  double nxs[3];
  double nxxi[3];
  double vxs[3];
  double vxxi[3];
  myb_vec3_cross(n, s, nxs);
  myb_vec3_cross(n, xi, nxxi);
  myb_vec3_cross(bv, s, vxs);
  myb_vec3_cross(bv, xi, vxxi);
  for (int i = 0; i < 3; ++i) {
    acc[i] += rr_n * n[i] + rr_v * bv[i] + rr_nxs * nxs[i] + rr_nxxi * nxxi[i] + rr_vxs * vxs[i] +
              rr_vxxi * vxxi[i];
  }
}

myb_status myb_internal_pn_higher(const myb_pn_binary* b, const double x[3], const double v[3],
                                  const double chi1[3], const double chi2[3], double a[3],
                                  double w1[3], double w2[3]) {
  MYB_CHECK(b != NULL && x != NULL && v != NULL && chi1 != NULL && chi2 != NULL && a != NULL &&
            w1 != NULL && w2 != NULL);
  const unsigned orders = b->orders;
  const double c = b->c;
  const double gm = b->gm1 + b->gm2;
  const double mass = gm / (c * c); /* G m / c^2: the unit of length */
  const double nu = b->gm1 * b->gm2 / (gm * gm);
  const double x1 = b->gm1 / gm;
  const double x2 = b->gm2 / gm;
  const double dm = (b->gm1 - b->gm2) / gm;
  double xh[3];
  double bv[3];
  for (int i = 0; i < 3; ++i) {
    xh[i] = x[i] / mass;
    bv[i] = v[i] / c;
  }
  double acc[3] = {0.0, 0.0, 0.0}; /* in units c^2 / (G m / c^2) */
  if (orders & (MYB_PN_4 | MYB_PN_4RR)) {
    const myb_status st =
        tail_acceleration(nu, xh, bv, (orders & MYB_PN_4) != 0u, (orders & MYB_PN_4RR) != 0u, acc);
    if (st != MYB_OK) {
      return st;
    }
  }
  if (orders & (MYB_PN_SO25 | MYB_PN_SO35 | MYB_PN_SORR)) {
    const double rh = myb_vec3_norm(xh);
    const double ri = 1.0 / rh;
    const double n[3] = {xh[0] * ri, xh[1] * ri, xh[2] * ri};
    const double rd = myb_vec3_dot(n, bv);
    const double v2 = myb_vec3_dot(bv, bv);
    double s[3];
    double z[3];
    for (int i = 0; i < 3; ++i) {
      s[i] = x1 * x1 * chi1[i] + x2 * x2 * chi2[i];
      z[i] = x2 * chi2[i] - x1 * chi1[i];
    }
    if (orders & (MYB_PN_SO25 | MYB_PN_SO35)) {
      spin_orbit_terms(orders, nu, dm, ri, rd, v2, n, bv, s, z, acc);
      double nxv[3];
      myb_vec3_cross(n, bv, nxv);
      const double k = c / mass; /* the unit of angular velocity */
      const double al1 = k * precession_higher(orders, nu, dm, ri, rd, v2);
      const double al2 = k * precession_higher(orders, nu, -dm, ri, rd, v2);
      for (int i = 0; i < 3; ++i) {
        w1[i] += al1 * nxv[i];
        w2[i] += al2 * nxv[i];
      }
    }
    if (orders & MYB_PN_SORR) {
      double xi[3];
      for (int i = 0; i < 3; ++i) {
        xi[i] = nu * (chi1[i] + chi2[i]);
      }
      spin_orbit_reaction(nu, ri, rd, v2, n, bv, s, xi, acc);
    }
  }
  const double unit = c * c / mass;
  for (int i = 0; i < 3; ++i) {
    a[i] += unit * acc[i];
  }
  return MYB_OK;
}

//! Writes the declarations of the crate `myb-sys` from the public headers of myb.
//!
//! The headers are read for one fixed target, so that the text does not depend on the machine
//! that generates it: what differs between platforms comes through the types of
//! `std::os::raw` (`c_long`) and `usize`, which Rust resolves where the crate is built.
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const BANNER: &str = "// Generated by bindings/rust/tools/generate from the public headers of \
myb. Do not edit.";

fn builder(root: &Path) -> bindgen::Builder {
    bindgen::Builder::default()
        .clang_arg(format!("-I{}", root.join("include").display()))
        .clang_args(["-DMYB_STATIC", "-std=c17", "-ffreestanding"])
        .clang_arg("--target=x86_64-unknown-linux-gnu")
        .layout_tests(false)
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .derive_default(true)
        .derive_debug(true)
        .derive_copy(true)
        .generate_comments(false)
        .raw_line(BANNER)
}

/// The declarations of the core library.
fn core(root: &Path) -> String {
    builder(root)
        .header(root.join("include/myb/myb.h").display().to_string())
        .allowlist_function("myb_.*")
        .allowlist_type("myb_.*")
        .allowlist_var("MYB_.*")
        .generate()
        .expect("the headers of myb")
        .to_string()
}

/// What the header of a module of ext/ adds to them.
fn extension(root: &Path, name: &str) -> String {
    let directory = root.join("ext").join(name);
    let header = directory.join(format!("myb_{name}.h"));
    builder(root)
        .clang_arg(format!("-I{}", directory.display()))
        .header(header.display().to_string())
        .allowlist_file(format!(".*myb_{name}\\.h"))
        .allowlist_recursively(false)
        .raw_line("use crate::*;")
        .generate()
        .expect("the header of the module")
        .to_string()
}

fn main() -> ExitCode {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let check = arguments.iter().any(|a| a == "--check");
    let Some(root) = arguments.iter().find(|a| !a.starts_with("--")).map(PathBuf::from) else {
        eprintln!("usage: myb-generate <repository root> [--check]");
        return ExitCode::from(2);
    };
    let source = root.join("bindings/rust/myb-sys/src");
    let mut files = vec![("bindings.rs".to_string(), core(&root))];
    for name in ["ionosphere", "nrlmsise00", "sgp4", "troposphere"] {
        files.push((format!("ext_{name}.rs"), extension(&root, name)));
    }
    let mut stale = Vec::new();
    for (name, text) in &files {
        let path = source.join(name);
        // line ends as the repository keeps them
        let text = text.replace("\r\n", "\n");
        if check {
            let current = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
            if current != text {
                stale.push(name.clone());
            }
        } else {
            std::fs::write(&path, &text).expect("writing the declarations");
            println!("written {} ({} lines)", path.display(), text.lines().count());
        }
    }
    if !stale.is_empty() {
        eprintln!(
            "out of date: {}; run bindings/rust/tools/generate",
            stale.join(", ")
        );
        return ExitCode::from(1);
    }
    ExitCode::SUCCESS
}

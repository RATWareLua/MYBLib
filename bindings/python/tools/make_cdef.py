"""Writes the declarations of the C interface as the Python package reads them (cffi).

The public headers are run through the preprocessor of Clang with the two system headers
they include replaced by empty ones: what comes out is the library's own declarations and
nothing of the platform, the same text on every system. Nothing is written by hand, so the
package cannot drift from the headers; its tests regenerate the file and compare.

usage: python make_cdef.py [--clang <clang>] [--check] [<repository root>]
  --check  do not write: exit with 1 if the files in the package differ from what the
           headers give now
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HEADER = """/* Generated by bindings/python/tools/make_cdef.py from the public headers of myb %s:
 * the declarations of %s as cffi reads them. Do not edit. */
"""


def preprocess(clang, root, text, extra_includes=()):
    """The declarations that `text` (a few #include lines) brings in."""
    with tempfile.TemporaryDirectory() as fake:
        for name in ("stddef.h", "stdint.h"):
            open(os.path.join(fake, name), "w").close()
        command = [clang, "-E", "-P", "-x", "c", "-std=c17", "-nostdinc", "-I", fake,
                   "-I", os.path.join(root, "include"), "-DMYB_STATIC", "-DMYB_NODISCARD="]
        for directory in extra_includes:
            command += ["-I", directory]
        command.append("-")
        done = subprocess.run(command, input=text, capture_output=True, text=True, check=True)
    lines = [line.rstrip() for line in done.stdout.splitlines() if line.strip()]
    return "\n".join(lines) + "\n"


def version(root):
    core = open(os.path.join(root, "include", "myb", "core.h"), encoding="utf-8").read()
    parts = [int(re.search(r"#define MYB_VERSION_%s (\d+)" % name, core).group(1))
             for name in ("MAJOR", "MINOR", "PATCH", "TWEAK")]
    return parts


def generate(clang, root):
    """{file name in the package: its text}."""
    parts = version(root)
    label = ".".join(str(p) for p in parts)
    number = parts[0] * 1000000 + parts[1] * 10000 + parts[2] * 100 + parts[3]
    core = preprocess(clang, root, '#include "myb/myb.h"\n')
    defines = "".join("#define MYB_VERSION_%s %d\n" % (name, value)
                      for name, value in zip(("MAJOR", "MINOR", "PATCH", "TWEAK"), parts))
    defines += "#define MYB_VERSION_NUMBER %d\n" % number
    files = {"_cdef.h": HEADER % (label, "libmyb") + defines + core}
    # the optional libraries of ext/: what each adds to the declarations of the core
    ext = os.path.join(root, "ext")
    for name in sorted(os.listdir(ext)):
        header = os.path.join(ext, name, "myb_%s.h" % name)
        if not os.path.exists(header):
            continue
        both = preprocess(clang, root, '#include "myb/myb.h"\n#include "myb_%s.h"\n' % name,
                          [os.path.join(ext, name)])
        if not both.startswith(core):
            raise SystemExit("ext/%s: its header does not begin with the declarations of the core"
                             % name)
        files["_cdef_%s.h" % name] = HEADER % (label, "libmyb_" + name) + both[len(core):]
    return files


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--clang", default=os.environ.get("MYB_CLANG", "clang"))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("root", nargs="?", default=os.path.normpath(os.path.join(here, "..", "..", "..")))
    arguments = parser.parse_args()
    package = os.path.join(arguments.root, "bindings", "python", "myb")
    files = generate(arguments.clang, arguments.root)
    stale = []
    for name, text in files.items():
        path = os.path.join(package, name)
        if arguments.check:
            current = open(path, encoding="ascii").read() if os.path.exists(path) else None
            if current != text:
                stale.append(name)
        else:
            with open(path, "w", encoding="ascii", newline="\n") as f:
                f.write(text)
            print("written", path, len(text.splitlines()), "lines")
    if stale:
        print("out of date: %s; run bindings/python/tools/make_cdef.py" % ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
